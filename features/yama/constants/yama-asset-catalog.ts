function createPack(
  id: YamaExpressionPackId,
  label: string,
  expression: YamaExpression,
  minimumVariations: number,
  useCases: readonly string[],
  variants: readonly string[],
  fallbackExpression?: YamaExpression,
): YamaAssetPack {
  const assets = buildPlannedPackAssets(id, variants, fallbackExpression);
  return {
    id,
    label,
    expression,
    minimumVariations,
    useCases,
    variants,
    assets,
  };
}

