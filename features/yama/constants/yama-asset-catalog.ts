const THEMES: readonly YamaAssetTheme[] = ["light", "dark"];

function buildAssetId(
  packId: YamaExpressionPackId,
  variant: string,
  theme: YamaAssetTheme,
  version: number,
): string {
  return `yama_${packId}_${variant}_${theme}_v${version}`;
}

function buildPlannedPackAssets(
  packId: YamaExpressionPackId,
  variants: readonly string[],
  fallbackExpression?: YamaExpression,
): YamaAssetEntry[] {
  return variants.flatMap((variant) =>
    THEMES.map((theme) => {
      const id = buildAssetId(packId, variant, theme, 1);

      return {
        id,
        packId,
        variant,
        theme,
        version: 1,
        status: "planned",
        fallbackExpression,
      } satisfies YamaAssetEntry;
    }),
  );
}

